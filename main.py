class LiteratureBot:
    def __init__(self, token):
        self.token = token
        self.app = Application.builder().token(token).build()
        self.setup_handlers()
    
    def setup_handlers(self):
        self.app.add_handler(CommandHandler("start", self.start))
        self.app.add_handler(CallbackQueryHandler(self.button_click))
    
    async def start(self, update: Update, context: ContextTypes.DEFAULT_TYPE):
        """Запуск бота"""
        keyboard = []
        for key, book in LITERATURE_DB.items():
            keyboard.append([InlineKeyboardButton(
                f"📖 {book['title']}", 
                callback_data=f"book_{key}"
            )])
        
        reply_markup = InlineKeyboardMarkup(keyboard)
        await update.message.reply_text(
            "📚 <b>Добро пожаловать в подготовку к ЕГЭ по литературе!</b>\n\n"
            "Выберите произведение:\n\n"
            "💡 Режимы:\n"
            "• 📋 <b>Информация</b> - краткое содержание, персонажи, даты\n"
            "• ❓ <b>Тест</b> - 15 случайных вопросов",
            reply_markup=reply_markup,
            parse_mode="HTML"
        )
    
    async def button_click(self, update: Update, context: ContextTypes.DEFAULT_TYPE):
        """Обработка нажатия кнопок"""
        query = update.callback_query
        await query.answer()
        
        data = query.data
        
        if data.startswith("book_"):
            book_key = data.split("_", 1)[1]
            context.user_data['current_book'] = book_key
            book = LITERATURE_DB[book_key]
            
            keyboard = [
                [InlineKeyboardButton("📋 Информация", callback_data=f"info_{book_key}")],
                [InlineKeyboardButton("❓ Тестирование", callback_data=f"test_{book_key}")],
                [InlineKeyboardButton("⬅️ Назад", callback_data="back")]
            ]
            
            reply_markup = InlineKeyboardMarkup(keyboard)
            await query.edit_message_text(
                f"<b>📖 {book['title']}</b>\n"
                f"Автор: {book['author']}\n"
                f"Год: {book['year']}\n\n"
                f"Выберите режим:",
                reply_markup=reply_markup,
                parse_mode="HTML"
            )
        
        elif data.startswith("info_"):
            book_key = data.split("_", 1)[1]
            await self.show_info_menu(query, book_key)
        
        elif data.startswith("chapter_"):
            parts = data.split("_")
            book_key = "_".join(parts[1:-1])
            chapter_num = parts[-1]
            
            book = LITERATURE_DB[book_key]
            chapter_title = book['chapters'][chapter_num]
            
            info_text = f"<b>{book['title']} - {chapter_title}</b>\n\n"
            
            info_text += "<b>🎭 Главные персонажи:</b>\n"
            for char, desc in list(book['characters'].items())[:3]:
                info_text += f"• <b>{char}</b> - {desc}\n"
            
            info_text += "\n<b>📅 Ключевые даты:</b>\n"
            for date, event in list(book['key_dates'].items())[:2]:
                info_text += f"• {date}: {event}\n"
            
            info_text += "\n<b>💡 Основные идеи:</b>\n"
            for idea in book['main_ideas'][:3]:
                info_text += f"• {idea}\n"
            
            keyboard = [
                [InlineKeyboardButton("⬅️ К главам", callback_data=f"info_{book_key}")],
                [InlineKeyboardButton("⬅️ К книге", callback_data=f"book_{book_key}")]
            ]
            
            reply_markup = InlineKeyboardMarkup(keyboard)
            await query.edit_message_text(info_text, reply_markup=reply_markup, parse_mode="HTML")
        
        elif data.startswith("test_"):
            book_key = data.split("_", 1)[1]
            context.user_data['current_book'] = book_key
            context.user_data['test_questions'] = []
            context.user_data['test_answers'] = []
            context.user_data['test_score'] = 0
            context.user_data['test_index'] = 0
            
            all_questions = TEST_QUESTIONS.get(book_key, []) + ADDITIONAL_QUESTIONS.get(book_key, [])
            context.user_data['test_questions'] = random.sample(all_questions, min(15, len(all_questions)))
            
            await self.show_test_question(query, context)
        
        elif data.startswith("answer_"):
            answer_index = int(data.split("_")[1])
            
            question = context.user_data['test_questions'][context.user_data['test_index']]
            correct_answer = question['answer']
            
            if answer_index == correct_answer:
                context.user_data['test_score'] += 1
            
            context.user_data['test_index'] += 1
            
            if context.user_data['test_index'] < len(context.user_data['test_questions']):
                await self.show_test_question(query, context)
            else:
                await self.show_test_results(query, context)
        
        elif data == "back":
            await self.start(update, context)
    
    async def show_info_menu(self, query, book_key):
        """Показ меню информации"""
        book = LITERATURE_DB[book_key]
        
        keyboard = []
        for chapter_num, chapter_name in book['chapters'].items():
            keyboard.append([InlineKeyboardButton(
                f"📄 {chapter_name}", 
                callback_data=f"chapter_{book_key}_{chapter_num}"
            )])
        
        keyboard.append([InlineKeyboardButton("⬅️ К книге", callback_data=f"book_{book_key}")])
        
        reply_markup = InlineKeyboardMarkup(keyboard)
        
        info_text = f"<b>📚 {book['title']}</b>\n\n"
        info_text += f"<b>Основные идеи:</b>\n"
        for idea in book['main_ideas']:
            info_text += f"• {idea}\n"
        
        info_text += f"\n<b>Выберите главу для подробного изучения:</b>"
        
        await query.edit_message_text(info_text, reply_markup=reply_markup, parse_mode="HTML")
    
    async def show_test_question(self, query, context):
        """Показ вопроса теста"""
        questions = context.user_data['test_questions']
        index = context.user_data['test_index']
        question_data = questions[index]
        
        text = f"❓ <b>Вопрос {index + 1}/{len(questions)}</b>\n\n"
        text += f"<b>{question_data['q']}</b>\n\n"
        
        keyboard = []
        for i, option in enumerate(question_data['options']):
            keyboard.append([InlineKeyboardButton(option, callback_data=f"answer_{i}")])
        
        reply_markup = InlineKeyboardMarkup(keyboard)
        await query.edit_message_text(text, reply_markup=reply_markup, parse_mode="HTML")
    
    async def show_test_results(self, query, context):
        """Показ результатов теста"""
        book_key = context.user_data['current_book']
        book = LITERATURE_DB[book_key]
        score = context.user_data['test_score']
        total = len(context.user_data['test_questions'])
        percentage = int((score / total) * 100)
        
        if percentage >= 90:
            rating = "5️⃣ - Отлично!"
        elif percentage >= 75:
            rating = "4️⃣ - Хорошо!"
        elif percentage >= 60:
            rating = "3️⃣ - Удовлетворительно"
        else:
            rating = "2️⃣ - Нужно учить!"
        
        text = f"<b>📊 Результаты теста по '{book['title']}'</b>\n\n"
        text += f"Правильных ответов: <b>{score}/{total}</b>\n"
        text += f"Процент: <b>{percentage}%</b>\n\n"
        text += f"Оценка: {rating}\n\n"
        
        recommendations = {
            "5️⃣": "Отличное знание материала! 🎓",
            "4️⃣": "Хороший результат, но лучше повторить пропущенные темы",
            "3️⃣": "Необходимо систематическое изучение произведения",
            "2️⃣": "Рекомендуется начать с начала и изучить произведение полностью"
        }
        
        text += f"💬 Рекомендация: {recommendations.get(rating.split()[0], 'Попробуйте ещё раз!')}"
        
        keyboard = [
            [InlineKeyboardButton("🔄 Пройти тест заново", callback_data=f"test_{book_key}")],
            [InlineKeyboardButton("📖 В другое произведение", callback_data="back")]
        ]
        
        reply_markup = InlineKeyboardMarkup(keyboard)
        await query.edit_message_text(text, reply_markup=reply_markup, parse_mode="HTML")
    
    def run(self):
        """Запуск бота"""
        print("🚀 Бот запущен!")
        self.app.run_polling()

